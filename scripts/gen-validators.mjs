// Generates extension/src/protocol/validators.gen.js — ajv validators
// pre-compiled to plain JS via ajv/dist/standalone. Required because MV3
// extension pages run under a CSP that forbids eval/Function, which is how
// ajv builds validators at runtime. Regenerate whenever the schema changes:
//
//   node scripts/gen-validators.mjs           # write
//   node scripts/gen-validators.mjs --check   # verify committed file is fresh
//
// strictRequired stays off for the same reason as validate.ts documents.
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "extension/src/protocol/validators.gen.js");
const OUT_DTS = join(root, "extension/src/protocol/validators.gen.d.ts");
const schema = JSON.parse(
  readFileSync(join(root, "protocol/schemas/envelope.schema.json"), "utf8"),
);

const ajv = new Ajv2020({
  allErrors: false,
  strict: true,
  strictRequired: false,
  code: { source: true, esm: true },
});
ajv.addSchema(schema, "envelope");

// standalone() takes export-name -> schema-id (it looks each up with
// getSchema internally); compiling here just ensures the ids resolve.
const validators = {
  validateMessage: "envelope",
  validatePlayerState: "envelope#/$defs/playerState",
  validateSearchSongsResult: "envelope#/$defs/searchSongsResult",
  validateSearchHistory: "envelope#/$defs/searchHistory",
  validateTargetsListResult: "envelope#/$defs/targetsListResult",
};
for (const [name, id] of Object.entries(validators)) {
  if (!ajv.getSchema(id)) {
    throw new Error(`schema compile produced no validator: ${name} (${id})`);
  }
}

const header = `// Generated by scripts/gen-validators.mjs from
// protocol/schemas/envelope.schema.json — do not edit. Regenerate with
// \`npm run gen:validators\` whenever the schema changes. No runtime eval:
// MV3 CSP forbids it.
`;
const code = header + standaloneCode(ajv, validators);

// Declaration twin so strict TS consumers see typed validators.
const dts = `${header.replaceAll("//", "//")}import type { ErrorObject } from "ajv";

type ValidateFn = ((data: unknown, ctx?: object) => boolean) & {
  errors?: ErrorObject[] | null;
};

export declare const validateMessage: ValidateFn;
export declare const validatePlayerState: ValidateFn;
export declare const validateSearchSongsResult: ValidateFn;
export declare const validateSearchHistory: ValidateFn;
export declare const validateTargetsListResult: ValidateFn;
`;

if (process.argv.includes("--check")) {
  const stale =
    readFileSync(OUT, "utf8") !== code ||
    readFileSync(OUT_DTS, "utf8") !== dts;
  if (stale) {
    console.error(
      "validators.gen.{js,d.ts} is stale — run `npm run gen:validators` and commit",
    );
    process.exit(1);
  }
  console.log("validators.gen.js is up to date");
} else {
  writeFileSync(OUT, code);
  writeFileSync(OUT_DTS, dts);
  console.log(`wrote ${OUT} (+ .d.ts)`);
}
